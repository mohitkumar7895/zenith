// Helper functions for Bihar districts
export function getBiharDistrictBySlug(slug: string): BiharDistrict | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().trim();
  return BIHAR_DISTRICTS.find((d) => d.slug === clean);
}

export function getAllBiharDistrictSlugs(): string[] {
  return BIHAR_DISTRICTS.map((d) => d.slug);
}

export function getBiharDistrictsByDivision(division: string): BiharDistrict[] {
  return BIHAR_DISTRICTS.filter((d) => d.division.toLowerCase() === division.toLowerCase());
}

export function getBiharDistrictsByZone(zone: string): BiharDistrict[] {
  return BIHAR_DISTRICTS.filter((d) => d.zone === zone);
}

