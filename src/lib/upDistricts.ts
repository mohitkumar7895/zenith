export function getDistrictBySlug(slug: string): UPDistrict | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().trim();
  return UP_DISTRICTS.find((d) => d.slug === clean);
}

export function getAllDistrictSlugs(): string[] {
  return UP_DISTRICTS.map((d) => d.slug);
}

