// Helper functions for All-India districts
export function getIndiaDistrictBySlug(slug: string): IndiaDistrict | undefined {
  if (!slug) return undefined;
  const clean = slug.toLowerCase().trim();
  return INDIA_DISTRICTS.find((d) => d.slug === clean);
}

export function getAllIndiaDistrictSlugs(): string[] {
  return INDIA_DISTRICTS.map((d) => d.slug);
}

export function getIndiaDistrictsByState(state: string): IndiaDistrict[] {
  return INDIA_DISTRICTS.filter((d) => d.state.toLowerCase() === state.toLowerCase());
}

